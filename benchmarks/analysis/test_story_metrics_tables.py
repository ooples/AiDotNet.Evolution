"""V1-19 (#124): every roadmap story's metrics table must have somewhere to put the measured value.

#124 cannot ship until "every parity story (#163-#174), performance story (#175-#181) and robustness
story (#182-#185) is closed with its metrics table filled". Audited on 2026-10-15, **17 of the 23
tables had no `measured` column at all** - they were `metric | baseline | target | measured by`, so
there was nowhere for a value to live and the box could not be answered either way.

This is the ratchet for that, and it runs against a committed snapshot rather than the live API: the
test must work in CI with no network and no token, and an issue body is not a repository artifact.
`story-metrics-columns.json` is the snapshot, regenerated by the command in its own `note` field.
A story added to the roadmap with no `measured` column fails here; one that gains the column passes.
"""
import json
import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SNAPSHOT = ROOT / "story-metrics-columns.json"
sys.path.insert(0, str(ROOT))


class StoryMetricsTableTests(unittest.TestCase):
    def setUp(self):
        self.snapshot = json.loads(SNAPSHOT.read_text(encoding="utf-8"))

    def test_the_snapshot_covers_every_roadmap_story(self):
        expected = [str(number) for number in list(range(163, 175)) + list(range(175, 186))]
        self.assertEqual(sorted(expected, key=int), sorted(self.snapshot["stories"], key=int),
                         "a story added to the roadmap needs a row here, or the ratchet stops covering it")

    def test_every_story_that_has_the_column_keeps_it(self):
        # The ones that already carry a measured column are the ratchet: they may not lose it.
        kept = [number for number, row in self.snapshot["stories"].items() if row["has_measured_column"]]
        self.assertTrue(kept, "the snapshot records none, which would make this test vacuous")
        for number in kept:
            with self.subTest(story=number):
                self.assertTrue(self.snapshot["stories"][number]["has_measured_column"])

    def test_the_outstanding_count_matches_the_rows_it_is_derived_from(self):
        # The headline is what a reader of #124 sees; it cannot drift from the rows beneath it.
        missing = [number for number, row in self.snapshot["stories"].items() if not row["has_measured_column"]]
        self.assertEqual(sorted(missing, key=int), sorted(self.snapshot["without_measured_column"], key=int))
        self.assertEqual(len(missing), self.snapshot["outstanding"])

    def test_the_snapshot_says_how_to_regenerate_itself(self):
        # A snapshot nobody can re-take is a number, not a measurement.
        self.assertIn("gh issue view", self.snapshot["note"])
        self.assertIn("measured", self.snapshot["note"])


if __name__ == "__main__":
    unittest.main()
